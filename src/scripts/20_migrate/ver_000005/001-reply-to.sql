-- 版 5-1: どの発言への返答かを持つ
--
-- 話題が並行すると、どれへの返答か分からなくなる。to_connector_id は
-- 「誰に」しか持てず、「どの発言に」を持つ列が無かった。
--
-- 【ref_archived_seq と同じ形】
--   親の msg_seq を持つだけ。本文とは切り離す。本文の形を仕様にすると、
--   文言を直すたびに読む側が壊れる。
--
-- 【CHECK を付けない理由】
--   指す先が片付けられていることがある。存在を強いると、返信が付いた発言を
--   片付けられなくなる。画面は指す先が無ければ引用を出さないだけにする。
--
-- 【索引を張らない理由】
--   返信をたどるのは画面が持っている範囲の中だけで、全件から引くことがない。
--
-- 列の追加は ALTER TABLE で足りる。テーブルの作り直しは要らない。
--
-- 当て済みの環境では二度と実行されない。書き換えてはいけない
-- （指紋が食い違い、起動が止まる）。

